/**
 * Phase 1 — generate the shared chrome components from the real crawled markup.
 *
 * Verified by fingerprinting: <header>, <footer>, .popup-mobile-menu and #pop
 * (after normalising the per-request CSRF token) are byte-identical on all 162
 * pages, so they are genuine static chrome and are generated once.
 *
 * Components are GENERATED, not hand-typed, so class names, attribute order and
 * text nodes survive exactly.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { load } from 'cheerio';
import { htmlToJsx } from './lib/html-to-jsx.mjs';
import { mergeImportantStyles } from './lib/important-styles.mjs';

const RAW = new URL('../data/raw/index.html', import.meta.url);
const OUT = new URL('../components/chrome/', import.meta.url);

/** Chrome pieces to extract: [component name, selector, index] */
const PIECES = [
  ['Header', 'body > header.rbt-header', 0],
  ['MobileMenu', 'body > div.popup-mobile-menu', 0],
  ['Footer', 'body > footer.rbt-footer', 0],
  ['BackToTop', 'body > div.rbt-progress-parent', 0],
  ['LeadModal', 'body > div#pop', 0],
  ['CompareModal', 'body > div#fullscreenModal', 0],
  // The live markup contains TWO #loder divs (a duplicate-ID bug): one before the
  // content, one after. They differ slightly (aria-hidden, an inline margin), so
  // both are reproduced in their original positions. jQuery's $('#loder') targets
  // the first. Both are `modal fade`, i.e. display:none, so neither is visible.
  ['LoaderModalTop', 'body > div#loder', 0],
  ['LoaderModalBottom', 'body > div#loder', 1],
  ['FloatingCompareBtn', 'body > button#floatingCompareBtn', 0],
  ['WhatsAppFloat', 'body > a.srm-whatsapp-float', 0],
];

const HEADER_NOTE = `/**
 * GENERATED by scripts/gen-chrome.mjs from the live markup — do not hand-edit.
 * Regenerate with: node scripts/gen-chrome.mjs
 */`;

function componentSource(name, jsx) {
  // Single-root pieces render directly; multi-root would need a fragment.
  return `${HEADER_NOTE}\nexport default function ${name}() {\n  return (\n${indent(jsx, 4)}\n  );\n}\n`;
}

function indent(src, spaces) {
  const pad = ' '.repeat(spaces);
  return src.split('\n').map((l) => (l.trim() ? pad + l : l)).join('\n');
}

async function main() {
  await mkdir(OUT, { recursive: true });
  const html = await readFile(RAW, 'utf8');
  const $ = load(html);

  const allWarnings = [];
  const allImportant = [];

  for (const [name, selector, idx] of PIECES) {
    const el = $(selector).eq(idx);
    if (!el.length) {
      console.error(`  MISSING  ${name}  (${selector})`);
      continue;
    }
    const raw = $.html(el);
    const { jsx, warnings, importantStyles } = htmlToJsx(raw);
    await writeFile(new URL(`${name}.tsx`, OUT), componentSource(name, jsx), 'utf8');
    allWarnings.push(...warnings.map((w) => ({ ...w, component: name })));
    allImportant.push(...importantStyles);
    console.log(`  ${name.padEnd(20)} ${raw.length.toString().padStart(7)}b raw -> ${jsx.length}b jsx  (${warnings.length} warnings)`);
  }

  const merged = await mergeImportantStyles(allImportant, 'chrome');
  console.log(`  pixel-inline.css     +${merged.added} rules (${merged.total} total)`);

  // The two page-level <style> blocks that follow #pop / #fullscreenModal
  // override styles.css and MUST be preserved verbatim.
  const styleBlocks = $('body > style').toArray().map((el) => $(el).html() ?? '');
  const stylesSource = `${HEADER_NOTE}
/** Page-level <style> blocks lifted verbatim from the live markup. They override
 *  styles.css (several use !important) so they must render after it. */
export const CHROME_STYLE_BLOCKS: string[] = ${JSON.stringify(styleBlocks, null, 2)};
`;
  await writeFile(new URL('styleBlocks.ts', OUT), stylesSource, 'utf8');
  console.log(`  styleBlocks          ${styleBlocks.length} blocks, ${styleBlocks.reduce((a, b) => a + b.length, 0)}b`);

  await writeFile(
    new URL('../../data/chrome-warnings.json', new URL('x', OUT)),
    JSON.stringify(allWarnings, null, 2),
    'utf8'
  );

  const byType = {};
  for (const w of allWarnings) byType[w.type] = (byType[w.type] ?? 0) + 1;
  console.log('\nwarnings by type:', byType);
  for (const w of allWarnings.filter((x) => x.type === 'inline-handler')) {
    console.log(`  inline-handler  ${w.component}  ${w.attr}="${String(w.value).slice(0, 90)}"`);
  }
}

main();
