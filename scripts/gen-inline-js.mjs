/**
 * Phase 1 — extract the global inline <script> blocks into standalone files.
 *
 * Each block is emitted as its OWN file, never concatenated. This is deliberate:
 * in the original markup every block is a separate <script>, so a throw inside
 * one aborts only that block. (The homepage's updateFeeValue() genuinely does
 * throw a TypeError.) Concatenating would let one throw kill every later block
 * and silently change behaviour.
 *
 * Transforms applied (all invisible; see the approved plan):
 *   - DROP the bhashsms.com block entirely: it ships plaintext SMS credentials,
 *     is http:// on an https:// page (mixed-content blocked), and its `${phone}`
 *     is inside single quotes so it never interpolates. Dead + a live leak.
 *   - Neutralise the hard-coded Laravel CSRF token literal; the Next route
 *     handler ignores _token and uses an origin check instead.
 * Everything else is byte-for-byte verbatim.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { load } from 'cheerio';
import { stripOrigin } from './lib/html-to-jsx.mjs';

const RAW = new URL('../data/raw/index.html', import.meta.url);
const OUT = new URL('../public/assets/js/inline/', import.meta.url);

/** Blocks matching these are not ported at all. */
const DROP = [
  {
    test: (src) => src.includes('bhashsms.com'),
    reason: 'plaintext SMS credentials; mixed-content; dead code',
  },
];

/** Laravel CSRF tokens are 40-char alphanumerics inside the AJAX payload. */
function neutraliseToken(src) {
  return src.replace(/("_token"\s*:\s*)"[A-Za-z0-9]{32,}"/g, '$1""');
}

/**
 * Absolute URLs back to the live origin must become site-relative, or the clone
 * would POST its leads to the real site instead of this one. inline-06.js posts
 * to https://srmflexilearn.com/lead-submit.
 */
function localiseUrls(src) {
  return stripOrigin(src);
}

async function main() {
  await mkdir(OUT, { recursive: true });
  const $ = load(await readFile(RAW, 'utf8'));

  const blocks = $('body > script')
    .toArray()
    .filter((el) => !$(el).attr('src'))
    .map((el) => $(el).html() ?? '');

  const manifest = [];
  let n = 0;

  for (const raw of blocks) {
    const dropped = DROP.find((d) => d.test(raw));
    if (dropped) {
      console.log(`  DROP  block (${raw.length}b) — ${dropped.reason}`);
      manifest.push({ dropped: true, reason: dropped.reason, bytes: raw.length });
      continue;
    }

    const src = localiseUrls(neutraliseToken(raw));
    const changed = src !== raw;
    const name = `inline-${String(++n).padStart(2, '0')}.js`;
    await writeFile(new URL(name, OUT), src, 'utf8');
    manifest.push({ file: `/assets/js/inline/${name}`, bytes: src.length, tokenNeutralised: changed });
    console.log(`  ${name}  ${String(src.length).padStart(6)}b${changed ? '  (token neutralised)' : ''}  ${src.trim().slice(0, 46).replace(/\s+/g, ' ')}`);
  }

  const kept = manifest.filter((m) => !m.dropped);
  await writeFile(
    new URL('../data/inline-manifest.json', import.meta.url),
    JSON.stringify(manifest, null, 2),
    'utf8'
  );

  // Emit the ordered file list as a TS module the loader imports.
  const ts = `/** GENERATED by scripts/gen-inline-js.mjs — do not hand-edit. */
export const INLINE_SCRIPTS: string[] = ${JSON.stringify(kept.map((k) => k.file), null, 2)};
`;
  await writeFile(new URL('../lib/inline-scripts.ts', import.meta.url), ts, 'utf8');

  console.log(`\nkept ${kept.length} blocks, dropped ${manifest.length - kept.length}`);
}

main();
