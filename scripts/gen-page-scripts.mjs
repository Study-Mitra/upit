/**
 * Extract PAGE-SPECIFIC inline scripts, one set per route family.
 *
 * gen-inline-js.mjs captured only the global chrome scripts present on the
 * homepage. Several families ship their own initialisers on top of those, and
 * omitting them leaves real behaviour missing — the course pages' Swiper
 * carousel is never constructed, so its cards render as a static row.
 *
 * Emits public/assets/js/page/<family>-NN.js and lib/page-scripts.ts.
 */
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { load } from 'cheerio';
import { stripOrigin } from './lib/html-to-jsx.mjs';

const RAW = new URL('../data/raw/', import.meta.url);
const OUT = new URL('../public/assets/js/page/', import.meta.url);
const INLINE_DIR = new URL('../public/assets/js/inline/', import.meta.url);

const md5 = (s) => createHash('md5').update(s).digest('hex').slice(0, 10);

/** Normalise the per-request CSRF token so the same script hashes equal. */
const normalise = (s) =>
  s.replace(/("_token"\s*:\s*)"[A-Za-z0-9]{20,}"/g, '$1""').trim();

async function main() {
  await mkdir(OUT, { recursive: true });

  // Scripts already loaded globally must not be duplicated per page.
  const globalHashes = new Set();
  for (const f of await readdir(INLINE_DIR)) {
    globalHashes.add(md5(normalise(await readFile(new URL(f, INLINE_DIR), 'utf8'))));
  }
  const $home = load(await readFile(new URL('index.html', RAW), 'utf8'));
  $home('body > script').each((_, el) => {
    if (!$home(el).attr('src')) globalHashes.add(md5(normalise($home(el).html() ?? '')));
  });

  const inventory = JSON.parse(
    await readFile(new URL('../data/inventory.json', import.meta.url), 'utf8')
  );

  /**
   * Keyed by PAGE PATH, not by family. Within a family the script sets differ —
   * /course/online ships a tab handler the detail pages do not — and loading a
   * family-wide union would execute code the live page never runs.
   *
   * Files are content-hashed so identical scripts shared across pages (and
   * across families) are stored once.
   */
  const manifest = {};
  const written = new Set();

  for (const page of inventory.pages) {
    const $ = load(await readFile(new URL(page.file, RAW), 'utf8'));
    const files = [];

    for (const el of $('script').toArray()) {
      const $el = $(el);
      if ($el.attr('src')) continue;
      // JSON-LD is metadata, already emitted by app/layout.tsx.
      if (($el.attr('type') ?? '').includes('ld+json')) continue;
      const src = $el.html() ?? '';
      if (!src.trim()) continue;
      const norm = normalise(src);
      const hash = md5(norm);
      if (globalHashes.has(hash)) continue;

      const name = `p-${hash}.js`;
      if (!written.has(name)) {
        // Page scripts also carry absolute origin URLs in their AJAX calls.
        await writeFile(new URL(name, OUT), stripOrigin(norm), 'utf8');
        written.add(name);
      }
      files.push(`/assets/js/page/${name}`);
    }

    if (files.length) manifest[page.path] = files;
  }

  const perFamily = {};
  for (const page of inventory.pages) {
    if (!manifest[page.path]) continue;
    perFamily[page.family] = (perFamily[page.family] ?? 0) + 1;
  }
  for (const [f, n] of Object.entries(perFamily)) {
    console.log(`  ${f.padEnd(24)} ${String(n).padStart(3)} pages with page scripts`);
  }
  console.log(`  ${'unique script files'.padEnd(24)} ${written.size}`);

  const ts = `/** GENERATED by scripts/gen-page-scripts.mjs — do not hand-edit.
 *
 * Page-specific inline scripts, keyed by URL path. They run AFTER the whole
 * vendor chain (see components/VendorScripts.tsx), because they depend on
 * jQuery, Swiper and main.js already being present.
 *
 * Keyed per page rather than per family on purpose: script sets differ within a
 * family, and running a union would execute code the live page never runs.
 */
export const PAGE_SCRIPTS: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)};

export function pageScriptsFor(path: string): string[] {
  return PAGE_SCRIPTS[path] ?? [];
}
`;
  await writeFile(new URL('../lib/page-scripts.ts', import.meta.url), ts, 'utf8');
  console.log(`\nwrote lib/page-scripts.ts for ${Object.keys(manifest).length} families`);
}

main();
