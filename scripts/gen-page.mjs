/**
 * Generate a page-content component from a crawled HTML file.
 *
 * The content region is everything between the shared chrome: it starts after
 * .popup-mobile-menu and ends before the trailing #loder. Verified against the
 * crawl — the homepage wraps its content in <main class="main">, while other
 * templates emit bare sibling <div> sections, so the boundary is positional
 * rather than selector-based.
 *
 * Usage: node scripts/gen-page.mjs <raw-file-basename> <ComponentName> [outDir]
 *   node scripts/gen-page.mjs index HomeContent
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { load } from 'cheerio';
import { htmlToJsx } from './lib/html-to-jsx.mjs';
import { mergeImportantStyles } from './lib/important-styles.mjs';

const RAW_DIR = new URL('../data/raw/', import.meta.url);

/**
 * Slice the body's children down to just the page content.
 * @returns {{ html: string, tags: string[] }}
 */
export function extractContent($) {
  const children = $('body').children().toArray();

  const startIdx = children.findIndex((el) =>
    $(el).hasClass('popup-mobile-menu')
  );
  // The trailing #loder marks the start of the footer chrome.
  let endIdx = -1;
  for (let i = children.length - 1; i > startIdx; i--) {
    if ($(children[i]).attr('id') === 'loder') {
      endIdx = i;
      break;
    }
  }

  if (startIdx === -1 || endIdx === -1) {
    throw new Error(`could not locate content boundaries (start=${startIdx}, end=${endIdx})`);
  }

  const nodes = children.slice(startIdx + 1, endIdx).filter((el) => {
    // Inline scripts inside the content region are global chrome scripts,
    // already extracted to /assets/js/inline/* by gen-inline-js.mjs.
    if (el.tagName === 'script') return false;
    return true;
  });

  return {
    html: nodes.map((el) => $.html(el)).join('\n'),
    tags: nodes.map((el) => `${el.tagName}.${($(el).attr('class') || '').split(' ')[0]}`),
  };
}

const HEADER_NOTE = `/**
 * GENERATED by scripts/gen-page.mjs from the live markup — do not hand-edit.
 * Regenerate with: node scripts/gen-page.mjs <raw-basename> <ComponentName>
 */`;

function indent(src, spaces) {
  const pad = ' '.repeat(spaces);
  return src.split('\n').map((l) => (l.trim() ? pad + l : l)).join('\n');
}

async function main() {
  const [basename, componentName, outDir = '../components/pages/'] = process.argv.slice(2);
  if (!basename || !componentName) {
    console.error('usage: node scripts/gen-page.mjs <raw-basename> <ComponentName> [outDir]');
    process.exit(1);
  }

  const OUT = new URL(outDir, import.meta.url);
  await mkdir(OUT, { recursive: true });

  const $ = load(await readFile(new URL(`${basename}.html`, RAW_DIR), 'utf8'));
  const { html, tags } = extractContent($);
  const { jsx, warnings, importantStyles } = htmlToJsx(html);
  const merged = await mergeImportantStyles(importantStyles, componentName);

  const source = `${HEADER_NOTE}
export default function ${componentName}() {
  return (
    <>
${indent(jsx, 6)}
    </>
  );
}
`;
  await writeFile(new URL(`${componentName}.tsx`, OUT), source, 'utf8');

  const byType = {};
  for (const w of warnings) byType[w.type] = (byType[w.type] ?? 0) + 1;
  console.log(`${componentName}: ${html.length}b html -> ${jsx.length}b jsx`);
  console.log(`  top-level sections (${tags.length}):`);
  for (const t of tags) console.log(`    ${t}`);
  console.log(`  warnings:`, byType);
  console.log(`  pixel-inline.css: +${merged.added} rules (${merged.total} total)`);
  if (warnings.some((w) => w.type === 'inline-handler')) {
    const uniq = [...new Set(warnings.filter((w) => w.type === 'inline-handler').map((w) => `${w.attr}="${String(w.value).slice(0, 70)}"`))];
    for (const u of uniq.slice(0, 12)) console.log(`    handler ${u}`);
    if (uniq.length > 12) console.log(`    ... +${uniq.length - 12} more`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
